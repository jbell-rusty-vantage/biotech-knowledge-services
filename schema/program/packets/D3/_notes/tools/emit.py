"""D3 fixtures stage: writers for locators.yaml, assertions.yaml and intent.json (biotech-knowledge-intent.v1)."""
import json
from pathlib import Path

import yaml

from fxlib import MISSION, TODAY, RAW_NORM, XML_NORM, canon

HEADER = ("# {name} — {what} (D3 fixtures stage, A4, {today}). Generated by _notes/tools/build_fixtures.py from fresh captures;\n"
          "# every locator was re-selected against the captured bytes during the build (reselected: true).\n")


class Dumper(yaml.SafeDumper):
    pass


def _str(d, s):
    if "\n" in s:
        return d.represent_scalar("tag:yaml.org,2002:str", s, style="|")
    return d.represent_scalar("tag:yaml.org,2002:str", s)


Dumper.add_representer(str, _str)


def dump(obj):
    return yaml.dump(obj, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=4096, default_flow_style=False)


def ts(d):
    if d is None:
        return None
    return d if "T" in d else f"{d}T00:00:00Z"


def write_locators(fx, out: Path):
    doc = {
        "fixture": fx.name,
        "textBases": {"raw-capture/v1": RAW_NORM, "xml-textcontent/v1": XML_NORM},
        "selectorKinds": "kernel SelectorKind (verification.v1 kinds + WHOLE_SNAPSHOT); TEXT_QUOTE carries a TextPositionSelector refinement",
        "snapshots": [s.card() for s in fx.snaps.values()],
        "locators": list(fx.locs.values()),
    }
    out.write_text(HEADER.format(name=fx.name, what="locators", today=TODAY) + dump(doc), encoding="utf-8")


def write_assertions(fx, out: Path, extra=None):
    doc = {
        "fixture": fx.name,
        "producedByNote": (f"producedBy ids are FIXTURE-SCOPED ids ({MISSION} / {fx.run}), not real Mission Control missions; in "
                           "production they are the generating Activity's missionId / runId (00-DIRECTIVE section 4)."),
        "kernelPattern": ("packets/K/09-reasoning.md (A1): one Assertion = one subject, one object node or literal value, one asserter "
                          "(ASSERTED_BY), HAS_EVIDENCE -> SourceLocator (role, origin); a typed D3 edge is the projection of an accepted "
                          "Assertion (AssertedEdgeProperties.assertionUid). Structural edges carry no Assertion. One locator per reported "
                          "number on every STATED_IN Assertion of a StudyResult (evidence[].reportsField)."),
        "recordedTimeNote": "recordedFrom is service-assigned at write time; the fixture uses the capture date 2026-10-08.",
        "entities": list(fx.ents.values()),
        "assertions": [{k: v for k, v in a.items() if k != "inIntent"} for a in fx.asserts],
        "structuralEdges": fx.structural,
    }
    if extra:
        doc.update(extra)
    out.write_text(HEADER.format(name=fx.name, what="assertions", today=TODAY) + dump(doc), encoding="utf-8")


def _validity(vt):
    v = {}
    for k in ("validFrom", "validTo"):
        if vt.get(k):
            v[k] = ts(vt[k])
    for k in ("validFromPrecision", "validToPrecision", "validFromBasis", "validToBasis"):
        if vt.get(k):
            v[k] = vt[k]
    return v


def _core(a):
    c = {"predicate": a["predicate"], "polarity": a["polarity"], "basisKind": a["basisKind"], "speechAct": a["speechAct"],
         "validity": _validity(a["validTime"]), "uidSegment": a["uid"].split(":", 2)[2]}
    return c


def build_intent(fx, intent_id, actor="agent:d3-curation-agent", activity="INGESTION", proposals_filter=None, notes_extra=""):
    sources = []
    used_snaps = set()
    for s in fx.snaps.values():
        locs = []
        for l in fx.locs.values():
            if l["snapshot"] != s.ref:
                continue
            d = {"ref": l["ref"], "uid": l["uid"], "selectorKind": l["selectorKind"]}
            if l.get("section"):
                d["section"] = l["section"]
            d["quote"] = l["quote"][:4000]
            if l["selectorKind"] == "TEXT_QUOTE":
                d["quotePrefix"], d["quoteSuffix"] = l["quotePrefix"], l["quoteSuffix"]
                d["startOffset"], d["endOffset"] = l["startOffset"], l["endOffset"]
            props = {"selectorJson": l["selectorJson"], "selectorDigest": l["selectorDigest"],
                     "expectedSelectedContentDigest": l["expectedSelectedContentDigest"]}
            if l.get("textBasis"):
                props["textBasis"] = l["textBasis"]
            if l.get("reportsField"):
                props["reportsField"] = l["reportsField"]
            d["properties"] = props
            locs.append(d)
        snapprops = {"captureMethod": s.method, "captureTool": s.tool}
        if s.published_at:
            snapprops["publishedAt"] = s.published_at
        sources.append({
            "ref": s.ref,
            "source": {"uid": s.source_uid, "canonicalUri": s.uri, "title": s.title[:600], "sourceKind": s.source_kind,
                       "properties": {"genre": s.genre}},
            "snapshot": {"uid": s.uid, "observedAt": ts(TODAY), "retrievedAt": ts(TODAY), "contentHash": s.digest,
                         "contentHashBasis": "RAW_BYTES", "captureCompleteness": "COMPLETE", "properties": snapprops},
            "locators": locs,
        })
    subjects = []
    for e in fx.ents.values():
        tname = e["type"].split(".")[1]
        if e["intentMode"] == "new":
            d = {"ref": e["ref"], "mode": "new", "nodeType": tname, "name": e["name"][:600], "uidSegment": e["uid"].split(":", 2)[2],
                 "properties": {k: v for k, v in (e.get("properties") or {}).items() if v is not None},
                 "identifiers": e.get("identifiers", []), "onMatch": "review"}
            subjects.append(d)
        else:
            subjects.append({"ref": e["ref"], "mode": "resolved", "uid": e["uid"], "nodeType": tname})
    proposals, skipped = [], []
    for a in fx.asserts:
        if proposals_filter and not proposals_filter(a):
            continue
        ev = [x["locator"] for x in a["evidence"]]
        pid = f"p-{a['ref']}"
        if not a["inIntent"]:
            skipped.append(a)
            continue
        pt = a.get("projectsTo", {})
        rel = pt.get("relationshipType")
        if rel == "HAS_IDENTIFIER":
            v = a["value"]
            proposals.append({"proposalId": pid, "kind": "identifier.attach", "subjectRef": a["subject"]["ref"],
                              "identifier": {"scheme": v["scheme"], "issuer": v["issuer"], "value": v["value"]}, "evidence": ev})
        elif rel and pt["class"].startswith("asserted (state"):
            proposals.append({"proposalId": pid, "kind": "state.attach", "subjectRef": a["subject"]["ref"],
                              "stateRef": a["object"]["ref"], "relationshipType": rel, "assertion": _core(a), "evidence": ev})
        elif rel:
            p = {"proposalId": pid, "kind": "edge.assert", "relationshipType": rel, "fromRef": a["subject"]["ref"],
                 "toRef": a["object"]["ref"], "assertion": _core(a), "edgeProperties": pt.get("edgeProperties") or {},
                 "asserterRef": a["assertedBy"]["ref"], "evidence": ev}
            rat = a.get("note") or ""
            if a.get("qualifiers"):
                rat = (rat + " " if rat else "") + ("Assertion.qualifiers (no AssertionCore field in intent v1; "
                                                    "11-open-questions #30): " + " | ".join(a["qualifiers"]))
            if rat:
                p["rationale"] = rat[:2000]
            proposals.append(p)
        elif "value" in a:
            p = {"proposalId": pid, "kind": "assertion.literal", "subjectRef": a["subject"]["ref"], "predicate": a["predicate"],
                 "assertion": _core(a), "asserterRef": a["assertedBy"]["ref"], "evidence": ev}
            v = a["value"]
            if isinstance(v, bool):
                p["valueBoolean"] = v
            elif isinstance(v, (int, float)):
                p["valueNumber"] = v
            elif isinstance(v, str):
                p["valueString"] = v[:4000]
            elif isinstance(v, dict) and "number" in v:
                p["valueNumber"] = v["number"]
                if v.get("unit"):
                    p["unitCode"] = v["unit"]
            else:
                p["valueString"] = canon(v)[:4000]
            proposals.append(p)
        else:
            skipped.append(a)
    for s in fx.structural:
        proposals.append({"proposalId": f"p-s-{len(proposals)+1:03d}", "kind": "edge.structural", "relationshipType": s["relationshipType"],
                          "fromRef": s["from"]["ref"], "toRef": s["to"]["ref"], "properties": s["properties"]})
    notes = (f"Fixture intent for D3 fixture {fx.name} (fixtures stage, A4, {TODAY}); validated against packages/contracts "
             "IngestionIntent (zod) by _notes/tools/validate_intents.mjs. Real captures (contentHash over RAW_BYTES). ")
    if skipped:
        notes += ("Not expressible in biotech-knowledge-intent.v1 and therefore only in assertions.yaml (predicate-only Assertion "
                  "with an object node, claim occurrence, or a held proposal): " + "; ".join(f"{a['ref']} {a['predicate']}" for a in skipped) + ". ")
    notes += notes_extra
    intent = {"schemaVersion": "biotech-knowledge-intent.v1", "intentId": intent_id,
              "context": {"actor": {"kind": "agent", "id": actor},
                          "run": {"system": "mission-control", "runId": fx.run, "missionId": MISSION}, "activityKind": activity},
              "onStale": "fail", "sources": sources, "subjects": subjects, "proposals": proposals, "notes": notes[:4000]}
    return intent


def write_intents(fx, outdir: Path, intent_id, **kw):
    intent = build_intent(fx, intent_id, **kw)
    props = intent["proposals"]
    files = []
    if len(props) <= 200:
        (outdir / "intent.json").write_text(json.dumps(intent, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        files.append("intent.json")
    else:
        parts = [props[i:i + 200] for i in range(0, len(props), 200)]
        for i, part in enumerate(parts):
            it = dict(intent)
            it["intentId"] = f"{intent_id}-part{i+1}"
            it["proposals"] = part
            it["notes"] = (f"Part {i+1} of {len(parts)} (intent v1 caps proposals at 200). " + intent["notes"])[:4000]
            name = "intent.json" if i == 0 else f"intent-part{i+1}.json"
            (outdir / name).write_text(json.dumps(it, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
            files.append(name)
    return files, len(props)

#!/usr/bin/env node
// Generates the mechanical part of the query-pattern DDL from the assembled IR:
//   - one uniqueness constraint on `uid` per node type (69 in final_biotech_schema_v2),
//   - one relationship-property index on `assertionUid` per relationship type whose edge-property type has it,
//   - one relationship-property index on `lastWriterRunId` per relationship type whose edge-property type has it.
// The hand-chosen constraints, range indexes, fulltext and vector indexes live in final/query-patterns.md (section 0).
// Usage (from the S worktree root):
//   node schema/program/final/_work/gen-patterns-ddl.mjs C:/.../final/schema/final_biotech_schema_v2.ir.json C:/.../final/_work/patterns-ddl.cypher
import { readFileSync, writeFileSync } from 'node:fs';

const [irPath, outPath] = process.argv.slice(2);
if (!irPath || !outPath) {
  console.error('usage: gen-patterns-ddl.mjs <ir.json> <out.cypher>');
  process.exit(2);
}
const ir = JSON.parse(readFileSync(irPath, 'utf8'));
const epFields = Object.fromEntries(
  ir.edgePropertyTypes.map((e) => [e.name, new Set((e.properties || []).map((p) => p.storedName || p.name))]),
);
const lines = [];
lines.push(`// GENERATED by gen-patterns-ddl.mjs from ${ir.schemaDigest} — do not edit by hand.`);
lines.push('// Section A: uid uniqueness, one per node type.');
const nodes = [...ir.nodes].sort((a, b) => a.name.localeCompare(b.name));
for (const n of nodes) {
  lines.push(`CREATE CONSTRAINT uid_${n.name} IF NOT EXISTS FOR (n:${n.primaryLabel || n.name}) REQUIRE n.uid IS UNIQUE;`);
}
const rels = [...ir.relationshipTypes].sort((a, b) => a.type.localeCompare(b.type));
let nAssertion = 0;
let nWriter = 0;
lines.push('// Section B: relationship-property indexes (kernel P13): assertionUid resolves an episode to its authorizing Assertion;');
lines.push('// lastWriterRunId resolves an edge to the Activity (runId) that last wrote it.');
for (const r of rels) {
  const fields = new Set(r.propertiesTypes.flatMap((p) => [...(epFields[p] || [])]));
  if (fields.has('assertionUid')) {
    lines.push(`CREATE INDEX rel_${r.type}_assertion IF NOT EXISTS FOR ()-[r:${r.type}]-() ON (r.assertionUid);`);
    nAssertion++;
  }
  if (fields.has('lastWriterRunId')) {
    lines.push(`CREATE INDEX rel_${r.type}_writer IF NOT EXISTS FOR ()-[r:${r.type}]-() ON (r.lastWriterRunId);`);
    nWriter++;
  }
}
writeFileSync(outPath, lines.join('\n') + '\n');
console.log(
  JSON.stringify({ schemaDigest: ir.schemaDigest, uidConstraints: nodes.length, relAssertionIndexes: nAssertion, relWriterIndexes: nWriter, statements: lines.filter((l) => !l.startsWith('//')).length }),
);

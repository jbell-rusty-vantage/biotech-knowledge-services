#!/usr/bin/env node
/**
 * Rewrites the `populatedBy` ids of final/relationship-register.yaml to the merged action-space ids (ruling R-39),
 * using the top-level `aliases` map of final/tooling/action-space.yaml (D11's generator output, copied unchanged).
 *
 *   node schema/program/final/_work/rewrite-populatedby.mjs [--check] [--report <C:/abs/report.json>]
 *
 * Resolution of one populatedBy value `v` on an entry stamped `module: M`:
 *   1. aliases["M:v"]          the packet-local id as M's 08 table wrote it → its canonical id
 *   2. v itself                when v is already a canonical entry id (makes the rewrite idempotent)
 *   3. otherwise unresolved    the value is kept as written and listed; exit code 1
 * Duplicates produced by the merge (two local ids → one canonical id) are dropped, first occurrence kept.
 * Only the populatedBy list lines are touched (line-level edit; comments, ordering and quoting elsewhere stay as they
 * are). After the edit the script re-parses the file and checks that, with populatedBy removed, the document is deeply
 * equal to the input, and that every populatedBy id is an action-space entry id.
 * NOTE: final/relationship-register.yaml is generated by merge-registers.mjs. Since the fix stage (2026-10-09) the rewrite is
 * applied to the fragments, so a re-merge keeps it:
 *   for M in K D1 … D13: node …/rewrite-populatedby.mjs --file <C:/abs/final/_work/registers/M.relationship.yaml> --module M
 *   node …/merge-registers.mjs; node …/rewrite-populatedby.mjs --check   (must exit 0: the merged file is already canonical)
 * --file / --module: rewrite one fragment; --module is used for entries that carry no `module:` stamp.
 * --check: compute only; exit 1 if the file would change or an id is unresolved.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { isDeepStrictEqual } from "node:util";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const finalDir = resolve(fileURLToPath(new URL("..", import.meta.url)));
const require = createRequire(resolve(finalDir, "../../../packages/schema-workspace/package.json"));
const YAML = require("yaml");
const args = process.argv.slice(2);
const CHECK = args.includes("--check");
const reportPath = args.includes("--report") ? args[args.indexOf("--report") + 1] : null;

const optv = (n) => (args.includes(n) ? args[args.indexOf(n) + 1] : null);
const regFile = optv("--file") ? resolve(optv("--file")) : resolve(finalDir, "relationship-register.yaml");
const defaultModule = optv("--module");
const asFile = resolve(finalDir, "tooling/action-space.yaml");
const space = YAML.parse(readFileSync(asFile, "utf8"));
const ids = new Set(space.entries.map((e) => e.id));
const aliases = space.aliases ?? {};

const text = readFileSync(regFile, "utf8");
const eol = text.includes("\r\n") ? "\r\n" : "\n";
const lines = text.split(/\r?\n/);
const before = YAML.parse(text);

// populatedBy blocks are expected only under `relationships:`; refuse to run if any other section carries one
const owners = [];
for (const [key, val] of Object.entries(before)) {
  if (!Array.isArray(val)) continue;
  for (const it of val) if (it && typeof it === "object" && "populatedBy" in it) owners.push({ section: key, it });
}
const bad = owners.filter((o) => o.section !== "relationships");
if (bad.length) { console.error(`populatedBy outside relationships: ${bad.map((o) => o.section).join(", ")}`); process.exit(1); }
const rels = owners.map((o) => o.it);

const unresolved = [];
const changes = [];
let k = 0, valuesIn = 0, valuesOut = 0, viaAlias = 0, alreadyCanonical = 0, dupsDropped = 0, renamed = 0;
const out = [];
for (let i = 0; i < lines.length; i++) {
  const m = lines[i].match(/^(\s+)populatedBy:\s*$/);
  // fragments write the list in flow style on one line: `    populatedBy: [a, b]  # optional comment`
  const fm = m ? null : lines[i].match(/^(\s+)populatedBy:\s*(\[[^\]]*\])\s*(#.*)?$/);
  if (!m && !fm) { out.push(lines[i]); continue; }
  const rel = rels[k++];
  if (!rel) { console.error(`line ${i + 1}: more populatedBy blocks than parsed entries`); process.exit(1); }
  const raw = [];
  if (m) {
    out.push(lines[i]);
    const itemRe = new RegExp(`^${m[1]}  - (.+)$`);
    while (i + 1 < lines.length && itemRe.test(lines[i + 1])) raw.push(YAML.parse(lines[++i].match(itemRe)[1]));
  } else raw.push(...YAML.parse(fm[2]));
  const want = [].concat(rel.populatedBy).map(String);
  if (!isDeepStrictEqual(raw.map(String), want)) {
    console.error(`line ${i + 1}: populatedBy block of ${rel.module} ${rel.type} does not match the parsed value`);
    process.exit(1);
  }
  const mapped = [];
  for (const v of want) {
    valuesIn++;
    const key = `${rel.module ?? defaultModule}:${v}`;
    let c;
    if (aliases[key]) { c = aliases[key]; viaAlias++; }
    else if (ids.has(v)) { c = v; alreadyCanonical++; }
    else { c = v; unresolved.push({ module: rel.module, type: rel.type, from: rel.from, to: rel.to, id: v }); }
    if (c !== v) renamed++;
    if (mapped.includes(c)) { dupsDropped++; continue; }
    mapped.push(c);
  }
  valuesOut += mapped.length;
  if (!isDeepStrictEqual(mapped, want)) changes.push({ module: rel.module, type: rel.type, from: rel.from, to: rel.to, before: want, after: mapped });
  const q = (c) => (/^[a-z0-9][a-z0-9.-]*$/.test(c) ? c : JSON.stringify(c));
  if (m) for (const c of mapped) out.push(`${m[1]}  - ${q(c)}`);
  else out.push(`${fm[1]}populatedBy: [${mapped.map(q).join(", ")}]${fm[3] ? ` ${fm[3]}` : ""}`);
}
if (k !== rels.length) { console.error(`found ${k} populatedBy blocks, parsed ${rels.length}`); process.exit(1); }

const next = out.join(eol);
// verification: only populatedBy changed, every id resolves
const after = YAML.parse(next);
const strip = (doc) => ({ ...doc, relationships: doc.relationships.map(({ populatedBy, ...rest }) => rest) });
if (!isDeepStrictEqual(strip(before), strip(after))) { console.error("verification failed: a field other than populatedBy changed"); process.exit(1); }
const afterIds = after.relationships.flatMap((r) => [].concat(r.populatedBy ?? []).map(String));
const notInSpace = afterIds.filter((v) => !ids.has(v));
const used = [...new Set(afterIds)].sort();

const report = {
  register: regFile,
  actionSpace: { file: "final/tooling/action-space.yaml", entries: ids.size, aliases: Object.keys(aliases).length },
  entriesWithPopulatedBy: rels.length,
  valuesIn, valuesOut, viaAlias, alreadyCanonical, renamed, duplicatesDropped: dupsDropped,
  entriesChanged: changes.length,
  distinctActionSpaceIdsUsed: used.length,
  unresolved, notInActionSpaceAfter: [...new Set(notInSpace)],
  wouldChange: next !== text,
  idsUsed: used,
  changes,
};
console.log(JSON.stringify({ ...report, idsUsed: undefined, changes: undefined }, null, 1));
if (reportPath) writeFileSync(reportPath, JSON.stringify(report, null, 1) + "\n", "utf8");
if (CHECK) process.exit(next !== text || unresolved.length || notInSpace.length ? 1 : 0);
if (next !== text) writeFileSync(regFile, next, "utf8");
process.exit(unresolved.length || notInSpace.length ? 1 : 0);

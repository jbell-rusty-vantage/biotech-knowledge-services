export function parseDecisions(markdown) {
  const rows = [];
  for (const line of markdown.split("\n")) {
    const m = /^\| ([A-Z]+(?:-[A-Z0-9]+)+) \| (.*) \| (.*) \|$/.exec(line);
    if (!m) continue;
    const cls = /^([CGD])\/([S0-9,]+)/.exec(m[3].trim());
    rows.push({ id: m[1], closure: m[3].trim(), class: cls?.[1] ?? null, workPackages: cls ? cls[2].split(",") : [] });
  }
  return rows;
}

export function buildDecisionClosure({ decisionsMd, existing }) {
  const rows = parseDecisions(decisionsMd);
  const problems = [];
  const out = rows.map((r) => {
    const s01 = r.workPackages.some((w) => w === "S0" || w === "S1");
    const c = CLOSURE[r.id];
    if (s01 && !c) problems.push(`decision ${r.id} (${r.closure.slice(0, 20)}) is S0/S1-owned and has no closure row`);
    const artifacts = c ? c[0] : [];
    for (const a of artifacts) {
      if (a.startsWith("BKS ")) continue;
      for (const p of a.split(", ")) if (!p.includes("*") && existing && !existing.has(p)) problems.push(`decision ${r.id}: artifact ${p} is not in the release`);
    }
    return {
      id: r.id,
      class: r.class,
      workPackages: r.workPackages,
      s1Scope: s01,
      releaseArtifacts: artifacts,
      s1Disposition: c ? c[1] : s01 ? null : "not S0/S1-owned (other work packages carry it)",
      evidenceStillOwedBy: r.workPackages.filter((w) => w !== "S0" && w !== "S1"),
    };
  });
  return { closure: { format: "bks-decision-closure.v1", entries: out.length, s01Entries: out.filter((x) => x.s1Scope).length, rows: out }, problems, ids: rows.map((r) => r.id) };
}

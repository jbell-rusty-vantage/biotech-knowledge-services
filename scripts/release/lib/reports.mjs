// FU-12: Subjectable usage audit (no removals)
// ==================================================================================================
export function buildSubjectableAudit({ model, predicates, nodeRegister, identifierSchemes, assessments }) {
  const implementers = model.interfaces.get("Subjectable")?.implementers ?? [];
  const active = new Set(identifierSchemes.schemes.filter((s) => s.writeStatus === "active").map((s) => s.code));
  const subkinds = assessments ? Object.values(assessments.subkinds ?? {}) : [];
  const rows = implementers.sort().map((type) => {
    const asSubject = [];
    const asObject = [];
    for (const p of predicates.predicates.filter((x) => x.status === "registered")) {
      if (asList(p.subjectTypes).map(registerTypeName).includes(type)) asSubject.push({ predicate: p.predicate, questions: asList(p.questions) });
      if (asList(p.objectTypes).map(registerTypeName).includes(type)) asObject.push({ predicate: p.predicate, questions: asList(p.questions) });
    }
    const assessed = subkinds.filter((s) => asList(s.admissibleSubjects).includes(type)).map((s) => s.subkind);
    const reg = nodeRegister.nodes.find((n) => n.name === type);
    const schemes = asList(reg?.identifierSchemes).map((s) => String(s).split(" ")[0]).filter((s) => active.has(s));
    const questions = [...new Set([...asSubject, ...asObject].flatMap((x) => x.questions))].sort();
    const used = asSubject.length + asObject.length + assessed.length + schemes.length > 0;
    return {
      type,
      module: model.nodes.get(type)?.module,
      assertionSubjectOf: asSubject.map((x) => x.predicate).sort(),
      assertionObjectOf: asObject.map((x) => x.predicate).sort(),
      assessmentTargetOf: assessed.sort(),
      identifierHolderFor: schemes.sort(),
      questions,
      justification: used ? (questions.length ? "used: registered predicate/assessment/identifier use with registered questions" : "used: registered predicate/assessment/identifier use; no question id recorded on the registry row") : "none: no registered use found; candidate for a separately reviewed future removal (not removed: FU-12)",
    };
  });
  return {
    format: "bks-subjectable-audit.v1",
    decision: "FU-12 (C/S0,S1), OD-01, R-18",
    rule: "per implementer: the registered question that uses it as subject or object of an Assertion, target of an Assessment, or identifier holder (active scheme), or none; no type is removed to meet a superseded metric",
    implementers: rows.length,
    used: rows.filter((r) => r.justification.startsWith("used")).length,
    none: rows.filter((r) => r.justification.startsWith("none")).map((r) => r.type),
    assessmentsRegistryPresent: Boolean(assessments),
    rows,
  };
}


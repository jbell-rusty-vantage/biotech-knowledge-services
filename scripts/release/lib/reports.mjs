// Predicate registry report (MD-X-02, MD-X-03, FU-13)
// ==================================================================================================
export function buildPredicateReport({ predicates, corrections, model, releaseId = "biotech-schema-v2.0.0" }) {
  const disp = corrections.predicateDispositions ?? [];
  const candidates = predicates.predicates.filter((p) => p.release?.decision === "MD-X-03 (a)");
  const registrarFlags = disp.filter((d) => d.decision === "MD-X-03 (b)" || (d.decision === "MD-X-03 (c)" && d.registrarCheck));
  const typeExists = (t) => model.nodes.has(t) || model.interfaces.has(t) || model.unions.has(t);
  const endpointProblems = [];
  for (const p of predicates.predicates.filter((x) => x.status === "registered")) {
    for (const t of asList(p.subjectTypes)) if (!typeExists(registerTypeName(t))) endpointProblems.push(`${p.predicate}: subject type ${t} not in the SDL`);
    for (const t of asList(p.objectTypes)) if (!typeExists(registerTypeName(t))) endpointProblems.push(`${p.predicate}: object type ${t} not in the SDL`);
  }
  const statusCounts = {};
  for (const p of predicates.predicates) {
    const s = p.status.split(":")[0];
    statusCounts[s] = (statusCounts[s] ?? 0) + 1;
  }
  const report = {
    format: "bks-predicate-registry-report.v1",
    decisions: ["MD-X-02", "MD-X-03", "FU-13", "FU-14 (f)"],
    totals: { entries: predicates.predicates.length, byStatus: statusCounts },
    proposedNewCandidates: {
      expected: 35,
      accounted: candidates.length,
      registered: candidates.filter((p) => p.status === "registered").map((p) => ({ predicate: p.predicate, kind: p.kind, registrar: p.registrar, field: p.field ?? null, change: p.release.change })),
      rejected: candidates.filter((p) => p.status !== "registered").map((p) => ({ predicate: p.predicate, status: p.status, replacedBy: asList(p.replacedBy), fixtureEdit: p.fixtureEdit ?? null })),
    },
    registrarFlags: {
      expectedPerOpenQuestions: 33,
      atCandidateRegistry: registrarFlags.length,
      note: "open-questions MD-X-03 (b) counted 33 at the first close-out; the refreshed candidate registry (`/names|outside/` on registrarCheck, the build-predicates.mjs rule) has 32 rows; every one is listed here",
      kept: registrarFlags.filter((d) => d.change.startsWith("registrar") && d.change.includes("kept")).map((d) => ({ predicate: d.predicate, registrar: d.registrar, reason: d.change })),
      moved: registrarFlags.filter((d) => d.change.startsWith("registrar moved")).map((d) => ({ predicate: d.predicate, from: d.from, to: d.to })),
      resolvedAsDuplicate: registrarFlags.filter((d) => d.decision === "MD-X-03 (c)").map((d) => ({ predicate: d.predicate, change: d.change })),
    },
    duplicates: disp.filter((d) => d.decision === "MD-X-03 (c)").map((d) => ({ predicate: d.predicate, change: d.change })),
    measures: disp.filter((d) => d.decision === "MD-X-03 (e)"),
    fu14f: disp.filter((d) => d.decision === "FU-14 (f)"),
    endpointCheck: { rule: "every registered predicate's subject and object types exist in the SDL (FU-13)", problems: endpointProblems },
  };
  const problems = [];
  if (report.proposedNewCandidates.accounted !== 35) problems.push(`MD-X-03: ${report.proposedNewCandidates.accounted} of 35 proposed-new candidates accounted`);
  if (statusCounts["proposed-new"]) problems.push("proposed-new entries remain");
  problems.push(...endpointProblems);
  return { report, problems, markdown: predicateMarkdown(report, releaseId) };
}

function predicateMarkdown(r, releaseId) {
  const rows = (list, cols) => list.map((x) => `| ${cols.map((c) => String(Array.isArray(x[c]) ? x[c].join(", ") : x[c] ?? "")).join(" | ")} |`).join("\n");
  return `# Predicate registry report (release ${releaseId})

GENERATED by scripts/release/generate.mjs (lib/reports.mjs). Decisions: ${r.decisions.join(", ")}. Machine form: \`predicate-registry-report.json\`.

Totals: ${r.totals.entries} entries; ${Object.entries(r.totals.byStatus).map(([k, v]) => `${k} ${v}`).join(", ")}.

## The 35 proposed-new candidates (MD-X-03 a): ${r.proposedNewCandidates.accounted} accounted, no blanket promotion

Registered (${r.proposedNewCandidates.registered.length}):

| predicate | kind | registrar | field | change |
| --- | --- | --- | --- | --- |
${rows(r.proposedNewCandidates.registered, ["predicate", "kind", "registrar", "field", "change"])}

Rejected with a re-key target (${r.proposedNewCandidates.rejected.length}; fixture re-keys are S3 / FU-03):

| predicate | status | replaced by |
| --- | --- | --- |
${rows(r.proposedNewCandidates.rejected, ["predicate", "status", "replacedBy"])}

## Registrar flags (MD-X-03 b): ${r.registrarFlags.atCandidateRegistry} rows

${r.registrarFlags.note}.

Kept as explicit exceptions (${r.registrarFlags.kept.length}):

| predicate | registrar | reason |
| --- | --- | --- |
${rows(r.registrarFlags.kept, ["predicate", "registrar", "reason"])}

Moved to the subject owner (R-52 rule 3) (${r.registrarFlags.moved.length}):

| predicate | from | to |
| --- | --- | --- |
${rows(r.registrarFlags.moved, ["predicate", "from", "to"])}

Resolved as duplicates (${r.registrarFlags.resolvedAsDuplicate.length}): ${r.registrarFlags.resolvedAsDuplicate.map((x) => x.predicate).join(", ")}.

## Duplicates and classification (MD-X-03 c, e; FU-14 f)

${[...r.duplicates, ...r.measures, ...r.fu14f].map((d) => `- ${d.predicate}: ${d.change}`).join("\n")}

## Endpoint check (FU-13)

${r.endpointCheck.rule}: ${r.endpointCheck.problems.length ? r.endpointCheck.problems.map((p) => `\n- ${p}`).join("") : "0 problems."}
`;
}


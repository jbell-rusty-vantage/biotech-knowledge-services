/**
 * Deterministic SDL assembly from module files (kernel first, then D1..D13 in numeric order, then an optional seam file).
 * Shared by scripts/assemble-schema.mjs (candidate run record, byte-compatible with the c7cf1235... baseline) and
 * scripts/release/generate.mjs (release sdl/assembled.graphql + sdl/assembled.manifest.json).
 */
import { basename } from "node:path";
import { graphql, sha256Hex } from "./common.mjs";

/** Module id for a module file name: kernel.graphql / K-*.graphql -> K, D7.graphql -> D7, seam*.graphql -> SEAM. */
export function moduleIdOf(file) {
  const b = basename(file, ".graphql");
  if (/^kernel/i.test(b) || /^K(-|$)/.test(b)) return "K";
  if (/^seam/i.test(b)) return "SEAM";
  const m = /^(D\d+)/.exec(b);
  return m ? m[1] : b;
}

export function moduleOrder(file) {
  const b = basename(file, ".graphql");
  if (/^kernel/i.test(b) || /^K(-|$)/.test(b)) return -1;
  if (/^seam/i.test(b)) return 1000;
  const m = /^D(\d+)/.exec(b);
  return m ? Number(m[1]) : 500;
}

const KIND = {
  ObjectTypeDefinition: "object",
  InterfaceTypeDefinition: "interface",
  UnionTypeDefinition: "union",
  EnumTypeDefinition: "enum",
  ScalarTypeDefinition: "scalar",
  InputObjectTypeDefinition: "input",
  DirectiveDefinition: "directive",
};

/**
 * @param {Array<{file: string, text: string}>} modules
 * @param {{ header: (files: string[]) => string }} options
 * @returns {{ text: string, manifest: object, modules: Array<object> }}
 */
export function assembleModules(modules, options) {
  const files = [...modules].sort((a, b) => moduleOrder(a.file) - moduleOrder(b.file) || a.file.localeCompare(b.file));
  if (!files.some((m) => moduleOrder(m.file) === -1)) throw new Error("no kernel module (kernel.graphql or K-*.graphql)");
  const seen = new Map();
  const parts = [];
  const info = [];
  for (const m of files) {
    const digest = sha256Hex(m.text);
    let doc;
    try {
      doc = graphql.parse(m.text.replace(/^#.*$/gm, ""), { noLocation: true });
    } catch (e) {
      throw new Error(`${m.file}: does not parse: ${e.message}`);
    }
    for (const def of doc.definitions) {
      const name = def.name?.value;
      if (!name) continue;
      if (seen.has(name)) throw new Error(`${m.file}: type ${name} already declared in ${seen.get(name)}`);
      seen.set(name, m.file);
    }
    info.push({ file: m.file, id: moduleIdOf(m.file), sha256: digest, bytes: Buffer.byteLength(m.text, "utf8"), definitions: doc.definitions.length });
    parts.push(`# ================================================================================================\n# MODULE ${basename(m.file, ".graphql")} (sha256:${digest.slice(0, 12)})\n# ================================================================================================\n\n${m.text.trim()}\n`);
  }
  const text = options.header(files.map((m) => basename(m.file, ".graphql"))) + parts.join("\n");
  // Locate each module and definition in the assembled text (1-based lines).
  const doc = graphql.parse(text, { noLocation: false });
  const lines = text.split("\n");
  const bannerLines = [];
  lines.forEach((l, i) => {
    const m = /^# MODULE (\S+) \(sha256:/.exec(l);
    if (m) bannerLines.push({ name: m[1], line: i + 1 });
  });
  const detailed = info.map((mod, idx) => {
    const start = bannerLines[idx].line - 1; // the ==== line above the banner
    const end = idx + 1 < bannerLines.length ? bannerLines[idx + 1].line - 3 : lines.length;
    return { ...mod, lineStart: start, lineEnd: end, definitionNames: [] };
  });
  for (const def of doc.definitions) {
    const name = def.name?.value;
    if (!name) continue;
    const line = def.loc.startToken.line;
    const mod = detailed.find((m) => line >= m.lineStart && line <= m.lineEnd);
    if (!mod) throw new Error(`definition ${name} at line ${line} is outside every module`);
    if (moduleIdOf(seen.get(name)) !== mod.id) throw new Error(`definition ${name}: banner module ${mod.id} disagrees with source file ${seen.get(name)}`);
    mod.definitionNames.push({ name, kind: KIND[def.kind] ?? def.kind, line });
  }
  return { text, modules: detailed, sha256: sha256Hex(text), types: seen.size };
}

/** Header of the candidate run record (scripts/assemble-schema.mjs); reproduces the c7cf1235... baseline bytes. */
export function candidateHeader(names) {
  return `# BellLabs biotech knowledge graph: CANDIDATE SCHEMA v2 (assembled from ${names.length} modules by scripts/assemble-schema.mjs)\n# Modules in order: ${names.join(", ")}\n# Do not edit this file; edit the module and re-assemble.\n\n`;
}

/** Header of a release assembly. */
export function releaseHeader(releaseId) {
  return (names) =>
    `# BellLabs biotech knowledge graph: SCHEMA RELEASE ${releaseId} (assembled from ${names.length} modules by scripts/release/generate.mjs)\n# Modules in order: ${names.join(", ")}\n# Do not edit this file; edit sdl/modules/<module>.graphql in the release sources and regenerate.\n\n`;
}

#!/usr/bin/env node
// Lead-only S9 operator tool: create (or check) the release principals on a Neo4j Enterprise instance.
//
//   node scripts/ops/aura-principals.mjs --dry-run                       # print the statements (no secrets), no connection
//   node scripts/ops/aura-principals.mjs --check                         # connect with the admin from .env, SHOW roles/users, no changes
//   node scripts/ops/aura-principals.mjs --apply --out <custody.json>    # create roles + users; passwords only in the custody file
//   BKS_BIOTECH_GRAPH_URI=bolt://127.0.0.1:7703 BKS_BIOTECH_GRAPH_USERNAME=neo4j BKS_BIOTECH_GRAPH_PASSWORD=... node scripts/ops/aura-principals.mjs --apply --out ... --allow-local
//   node scripts/ops/aura-principals.mjs --apply --builtin --out <custody.json>
//       Aura Professional: the console admin has USER MANAGEMENT + ASSIGN ROLE but no ROLE MANAGEMENT (CREATE ROLE is
//       refused, observed 2026-10-12). --builtin creates the same four users bound to Neo4j's built-in roles instead
//       (reader_public/reader_internal -> reader, writer -> publisher, migrator -> architect), then probes what each user
//       can actually do (write refusal, SHOW INDEXES/CONSTRAINTS, dbms.components, APOC functions) and records it.
//
// Roles: bks_reader_public, bks_reader_internal (statements generated by @bks/kg-ops read/rbac from the pinned release),
// bks_writer (executor: read + write, no DDL / user management), bks_migrator (writer + index/constraint/name management).
// Users: <role>_svc. Passwords: random, written only to --out (protected custody), never printed.
// Admin credentials come from process.env or the repository .env (BKS_BIOTECH_GRAPH_URI/BKS_BIOTECH_GRAPH_USERNAME/BKS_BIOTECH_GRAPH_PASSWORD).
import { randomBytes } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(here, "..", "..");
const requireKg = createRequire(resolve(REPO, "packages/kg-ops/package.json"));
const neo4j = requireKg("neo4j-driver");
const dotenv = requireKg("dotenv");
const { ReadModel, readerRoleStatements, READER_ROLES } = await import(resolve(REPO, "packages/kg-ops/dist/read/index.js").replace(/\\/g, "/").replace(/^([A-Za-z]):/, "file:///$1:"));

const args = new Set(process.argv.slice(2));
const opt = (name) => { const i = process.argv.indexOf(name); return i >= 0 ? process.argv[i + 1] : undefined; };
const dryRun = args.has("--dry-run");
const check = args.has("--check");
const apply = args.has("--apply");
const allowLocal = args.has("--allow-local");
const builtin = args.has("--builtin");
// Aura Professional mapping (probed 2026-10-12, runs/release-v2/custody/s9/aura-role-probes-2.json): Neo4j's plain built-in
// roles (reader/publisher/architect) cannot call dbms.components, db.* or APOC functions on Aura, which the GraphQL
// library, the read service and the writer fence need. Aura's own GraphQL Data API roles carry those grants:
//   graphql_app_read_only_<id>  : MATCH, SHOW INDEX/CONSTRAINT, dbms.components, db.*, APOC functions; write + DDL refused
//   graphql_app_read_write_<id> : the same plus WRITE; DDL refused
//   architect                   : WRITE + INDEX/CONSTRAINT management (no procedures) -> combined with read_only for the migrator
const AURA_ID = (uri0) => (uri0?.match(/\/\/([a-f0-9]+)\.databases\.neo4j\.io/) ?? [])[1];
const BUILTIN_FOR = (id) => ({
  [READER_ROLES.public]: [`graphql_app_read_only_${id}`],
  [READER_ROLES.internal]: [`graphql_app_read_only_${id}`],
  bks_writer: [`graphql_app_read_write_${id}`],
  bks_migrator: ["architect", `graphql_app_read_only_${id}`],
});
let BUILTIN = BUILTIN_FOR("<aura-id>");
const database = opt("--database") ?? "neo4j";
const out = opt("--out");
if (!dryRun && !check && !apply) { console.error("usage: --dry-run | --check | --apply --out <file> [--allow-local] [--database neo4j]"); process.exit(2); }

const env = { ...(existsSync(resolve(REPO, ".env")) ? dotenv.parse(readFileSync(resolve(REPO, ".env"))) : {}), ...process.env };
const uri = env.BKS_BIOTECH_GRAPH_URI;
const user = env.BKS_BIOTECH_GRAPH_USERNAME;
const pass = env.BKS_BIOTECH_GRAPH_PASSWORD;

const model = ReadModel.fromRelease();
const g = `GRAPH \`${database}\``;
const roles = {
  [READER_ROLES.public]: readerRoleStatements(model, "public", database),
  [READER_ROLES.internal]: readerRoleStatements(model, "internal", database),
  bks_writer: [
    "CREATE ROLE bks_writer IF NOT EXISTS",
    `GRANT ACCESS ON DATABASE \`${database}\` TO bks_writer`,
    `GRANT MATCH {*} ON ${g} TO bks_writer`,
    `GRANT WRITE ON ${g} TO bks_writer`,
    `GRANT NAME MANAGEMENT ON DATABASE \`${database}\` TO bks_writer`,
    `DENY INDEX MANAGEMENT ON DATABASE \`${database}\` TO bks_writer`,
    `DENY CONSTRAINT MANAGEMENT ON DATABASE \`${database}\` TO bks_writer`,
    "DENY LOAD ON ALL DATA TO bks_writer",
    "DENY EXECUTE PROCEDURE apoc.load.*, apoc.export.*, apoc.import.*, apoc.cypher.runFile*, apoc.periodic.*, dbms.*, gds.*, genai.* ON DBMS TO bks_writer",
  ],
  bks_migrator: [
    "CREATE ROLE bks_migrator IF NOT EXISTS",
    `GRANT ACCESS ON DATABASE \`${database}\` TO bks_migrator`,
    `GRANT MATCH {*} ON ${g} TO bks_migrator`,
    `GRANT WRITE ON ${g} TO bks_migrator`,
    `GRANT NAME MANAGEMENT ON DATABASE \`${database}\` TO bks_migrator`,
    `GRANT INDEX MANAGEMENT ON DATABASE \`${database}\` TO bks_migrator`,
    `GRANT CONSTRAINT MANAGEMENT ON DATABASE \`${database}\` TO bks_migrator`,
    "DENY LOAD ON ALL DATA TO bks_migrator",
    "DENY EXECUTE PROCEDURE dbms.security.*, gds.*, genai.* ON DBMS TO bks_migrator",
  ],
};
if (builtin) { const id = AURA_ID(env.BKS_BIOTECH_GRAPH_URI); if (!id) { console.error("--builtin needs an Aura BKS_BIOTECH_GRAPH_URI (<id>.databases.neo4j.io)"); process.exit(2); } BUILTIN = BUILTIN_FOR(id); }
const users = Object.fromEntries(Object.keys(roles).map((r) => [`${r}_svc`, builtin ? BUILTIN[r] : [r]]));

if (dryRun) {
  for (const [role, statements] of Object.entries(roles)) { console.log(`-- ${role}`); for (const s of statements) console.log(s); }
  for (const [u, r] of Object.entries(users)) console.log(`CREATE USER ${u} IF NOT EXISTS SET PASSWORD <secret> CHANGE NOT REQUIRED; GRANT ROLE ${r.join(", ")} TO ${u}`);
  console.log(`-- ${Object.values(roles).flat().length} role statements, ${Object.keys(users).length} users; release ${model.releaseId ?? "(pinned)"}`);
  process.exit(0);
}

if (!uri || !user || !pass) { console.error("admin credentials missing (BKS_BIOTECH_GRAPH_URI/BKS_BIOTECH_GRAPH_USERNAME/BKS_BIOTECH_GRAPH_PASSWORD)"); process.exit(2); }
const isAura = /databases\.neo4j\.io/.test(uri);
if (apply && !isAura && !allowLocal) { console.error("refusing --apply on a non-Aura target without --allow-local"); process.exit(3); }
if (apply && !out) { console.error("--apply requires --out <custody file>"); process.exit(2); }
console.log(`target: ${uri.replace(/^(\w+):\/\/([^/:@]+).*/, "$1://$2")} (${isAura ? "aura" : "local"}), database ${database}, mode ${apply ? "apply" : "check"}`);

const driver = neo4j.driver(uri, neo4j.auth.basic(user, pass));
const sys = driver.session({ database: "system" });
const summary = { target: uri.replace(/^(\w+):\/\/([^/:@]+).*/, "$1://$2"), database, createdAt: new Date().toISOString(), roles: {}, users: {} };
try {
  const existingRoles = new Set((await sys.run("SHOW ROLES YIELD role RETURN role")).records.map((r) => r.get("role")));
  const existingUsers = new Set((await sys.run("SHOW USERS YIELD user RETURN user")).records.map((r) => r.get("user")));
  for (const role of Object.keys(roles)) summary.roles[role] = { existedBefore: existingRoles.has(role) };
  for (const u of Object.keys(users)) summary.users[u] = { existedBefore: existingUsers.has(u) };
  if (check) { console.log(JSON.stringify(summary, null, 2)); }
  if (apply) {
    const secrets = {};
    summary.mode = builtin ? "builtin-roles" : "custom-roles";
    if (builtin) {
      for (const role of Object.keys(roles)) summary.roles[role] = { ...summary.roles[role], applied: 0, boundTo: BUILTIN[role], builtinExists: BUILTIN[role].every((b) => existingRoles.has(b)) };
      const missing = [...new Set(Object.values(BUILTIN).flat())].filter((r) => !existingRoles.has(r));
      if (missing.length) { console.error(`built-in roles missing on target: ${missing.join(", ")}`); process.exit(5); }
    } else {
      for (const [role, statements] of Object.entries(roles)) {
        for (const s of statements) await sys.run(s);
        summary.roles[role].applied = statements.length;
      }
    }
    for (const [u, r] of Object.entries(users)) {
      const pw = randomBytes(24).toString("base64url");
      secrets[u] = pw;
      if (existingUsers.has(u)) await sys.run(`ALTER USER ${u} SET PASSWORD $p CHANGE NOT REQUIRED`, { p: pw });
      else await sys.run(`CREATE USER ${u} SET PASSWORD $p CHANGE NOT REQUIRED`, { p: pw });
      for (const role of r) await sys.run(`GRANT ROLE \`${role}\` TO ${u}`);
      // exact role set: revoke anything else this user carries (except PUBLIC), e.g. a mapping used by an earlier run
      const current = (await sys.run("SHOW USERS YIELD user, roles WHERE user = $u RETURN roles", { u })).records[0]?.get("roles") ?? [];
      const revoked = [];
      for (const role of current) if (role !== "PUBLIC" && !r.includes(role)) { await sys.run(`REVOKE ROLE \`${role}\` FROM ${u}`); revoked.push(role); }
      summary.users[u].roles = r; summary.users[u].revoked = revoked;
    }
    // Proof: each user's privileges, and a reader write refusal.
    for (const u of Object.keys(users)) {
      try {
        const priv = await sys.run(`SHOW USER ${u} PRIVILEGES YIELD access, action, resource, segment RETURN count(*) AS c`);
        summary.users[u].privilegeRows = priv.records[0].get("c").toNumber();
      } catch (e) { summary.users[u].privilegeRows = { unavailable: e.code }; } // Aura Professional admin lacks SHOW PRIVILEGE
    }
    const reader = neo4j.driver(uri, neo4j.auth.basic(`${READER_ROLES.public}_svc`, secrets[`${READER_ROLES.public}_svc`]));
    const rs = reader.session({ database, defaultAccessMode: neo4j.session.WRITE });
    try { await rs.run("CREATE (:BksPrincipalProbe {synthetic: true})"); summary.readerWriteRefused = false; }
    catch (e) { summary.readerWriteRefused = /Forbidden|permission|denied|not allowed/i.test(String(e.message)); }
    finally { await rs.close(); await reader.close(); }
    // Capability probes per user (read-only; the write probe runs in a transaction that is always rolled back).
    const probes = {
      match: "MATCH (n) RETURN count(n) AS c",
      components: "CALL dbms.components() YIELD edition RETURN edition",
      showIndexes: "SHOW INDEXES YIELD name RETURN count(*) AS c",
      showConstraints: "SHOW CONSTRAINTS YIELD name RETURN count(*) AS c",
      apocConvertFormat: "RETURN apoc.date.convertFormat('2026-10-12', 'date', 'basic_date') AS d",
      apocLoadJson: "CALL apoc.load.json('file:///nonexistent.json') YIELD value RETURN count(*) AS c",
      apocTextJoin: "RETURN apoc.text.join(['a','b'], '-') AS t",
      gdsList: "CALL gds.list() YIELD name RETURN count(*) AS c",
      dbLabels: "CALL db.labels() YIELD label RETURN count(*) AS c",
      dbAwaitIndexes: "CALL db.awaitIndexes(1)",
      dbFulltext: "CALL db.index.fulltext.queryNodes('bks_nonexistent_probe_index', 'x') YIELD node RETURN count(*) AS c",
      dbmsListConfig: "CALL dbms.listConfig() YIELD name RETURN count(*) AS c",
      showUsers: "SHOW USERS YIELD user RETURN count(*) AS c",
      createIndex: "CREATE INDEX bks_principal_probe_idx IF NOT EXISTS FOR (n:BksPrincipalProbe) ON (n.synthetic)",
    };
    summary.probes = {};
    for (const u of Object.keys(users)) {
      const d = neo4j.driver(uri, neo4j.auth.basic(u, secrets[u]));
      const res = {};
      for (const [k, cy] of Object.entries(probes)) {
        const sess = d.session({ database, defaultAccessMode: neo4j.session.WRITE });
        const tx = sess.beginTransaction();
        try { const r = await tx.run(cy); res[k] = { ok: true, rows: r.records.length }; }
        catch (e) { res[k] = { ok: false, code: e.code, message: String(e.message).split("\n")[0].slice(0, 160) }; }
        finally { try { await tx.rollback(); } catch {} await sess.close(); }
      }
      // write probe: statement runs, transaction rolled back (nothing persists)
      const sess = d.session({ database, defaultAccessMode: neo4j.session.WRITE });
      const tx = sess.beginTransaction();
      try { await tx.run("CREATE (:BksPrincipalProbe {synthetic: true})"); res.write = { ok: true, rolledBack: true }; }
      catch (e) { res.write = { ok: false, code: e.code }; }
      finally { try { await tx.rollback(); } catch {} await sess.close(); await d.close(); }
      summary.probes[u] = res;
    }
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, JSON.stringify({ ...summary, secrets }, null, 2));
    console.log(JSON.stringify({ ...summary, secretsWrittenTo: out }, null, 2));
    if (summary.readerWriteRefused !== true) { console.error("reader write was NOT refused; investigate before use"); process.exit(4); }
  }
} finally { await sys.close(); await driver.close(); }

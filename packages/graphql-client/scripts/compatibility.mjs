#!/usr/bin/env node
/**
 * Writes src/compatibility.ts from the server's generated identity and operation registry, after proving that every
 * codegen persisted-document hash equals the server registry id of the same document (byte-identical normalization).
 * Fails when the client and server safelists differ. Run by `pnpm client:codegen` after graphql-codegen.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..");
const api = join(pkg, "..", "..", "apps", "graphql-api");
const identity = JSON.parse(readFileSync(join(api, "generated", "identity.json"), "utf8"));
const registry = JSON.parse(readFileSync(join(api, "operations", "operations.json"), "utf8"));
const persisted = JSON.parse(readFileSync(join(pkg, "src", "generated", "persisted-documents.json"), "utf8"));

const problems = [];
const registryIds = new Map(registry.operations.map((o) => [o.id, o]));
for (const [hash, document] of Object.entries(persisted)) {
  const op = registryIds.get(hash);
  if (!op) problems.push(`codegen document ${hash} is not in the server registry`);
  else if (op.document !== document) problems.push(`codegen document ${hash} (${op.name}) differs from the registry document`);
}
for (const op of registry.operations) if (!persisted[op.id]) problems.push(`registry operation ${op.name} ${op.id} has no generated client document`);
if (registry.releaseCompatibility.executableGraphqlDigest !== identity.executableGraphqlDigest) problems.push("registry and identity name different executables");
if (problems.length) {
  for (const p of problems) console.error(`compatibility: ${p}`);
  process.exit(1);
}

const operations = Object.fromEntries(registry.operations.map((o) => [o.name, { id: o.id, costClass: o.costClass }]));
const body = {
  releaseId: identity.releaseId,
  sourceMode: identity.sourceMode,
  schemaDigest: identity.schemaDigest,
  schemaReleaseDigest: identity.schemaReleaseDigest,
  productProjectionDigest: identity.productProjectionDigest,
  executableGraphqlDigest: identity.executableGraphqlDigest,
  operationRegistryDigest: identity.operationRegistryDigest,
  operations,
};
const text = `/* Generated by scripts/compatibility.mjs from apps/graphql-api/generated/identity.json and operations/operations.json. Do not edit. */

/** The exact server build this client was generated against (INTERFACES section 1 identities). */
export const compatibility = ${JSON.stringify(body, null, 2)} as const;

export type OperationName = keyof typeof compatibility.operations;
`;
writeFileSync(join(pkg, "src", "compatibility.ts"), text);
console.log(`wrote src/compatibility.ts (${registry.operations.length} operations, executable ${identity.executableGraphqlDigest}, registry ${identity.operationRegistryDigest})`);
